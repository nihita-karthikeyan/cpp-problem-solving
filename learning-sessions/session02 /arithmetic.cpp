// Sum, difference, product and decimal division of two numbers
#include <iostream>
using namespace std;

int main() {
    int a = 15;
    int b = 4;
    int sum = a + b;
    int difference = a - b;
    int product = a * b;
    double division = (double)a / b;
    cout << sum << " " << difference << " " << product << " " << division;
    return 0;
}
